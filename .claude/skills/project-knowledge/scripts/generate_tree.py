#!/usr/bin/env python3
"""Generate PROJECT_TREE.md — a compact, always-current knowledge base of the repo.

Everything in the output is derived from the repo itself so it never goes stale.
Run from the project root:  python .claude/skills/project-knowledge/scripts/generate_tree.py
"""

import re
import sys
from pathlib import Path

EXCLUDE_DIRS = {
    "target", "node_modules", ".git", "dist", "build", ".next",
    ".turbo", ".cargo", "__pycache__", ".pytest_cache", "coverage",
    ".vscode", ".idea", "gen",  # tauri codegen output
}

# Directories whose contents are noise — show the dir itself but not children.
COLLAPSE_DIRS = {"icons", "capabilities", "assets", "models"}

MAX_DEPTH = 4


def excluded(item: Path) -> bool:
    name = item.name
    if name in EXCLUDE_DIRS:
        return True
    # hidden files/dirs except .claude (worth showing so skills are discoverable)
    if name.startswith(".") and name != ".claude":
        return True
    return False


def tree_lines(root: Path, prefix: str = "", depth: int = 0) -> list[str]:
    lines: list[str] = []
    try:
        items = sorted(root.iterdir(), key=lambda p: (not p.is_dir(), p.name.lower()))
    except PermissionError:
        return lines
    items = [i for i in items if not excluded(i)]

    for i, item in enumerate(items):
        last = i == len(items) - 1
        connector = "\\-- " if last else "|-- "
        suffix = "/" if item.is_dir() else ""
        lines.append(f"{prefix}{connector}{item.name}{suffix}")
        collapse = item.name in COLLAPSE_DIRS and not (item / "Cargo.toml").exists()
        if item.is_dir() and not collapse and depth < MAX_DEPTH:
            extension = "    " if last else "|   "
            lines.extend(tree_lines(item, prefix + extension, depth + 1))
    return lines


def read_toml_field(cargo_toml: Path, field: str) -> str | None:
    """Cheap single-field extractor; avoids a toml dependency."""
    try:
        text = cargo_toml.read_text(encoding="utf-8")
    except OSError:
        return None
    m = re.search(rf'^{field}\s*=\s*"([^"]*)"', text, re.MULTILINE)
    return m.group(1) if m else None


def crate_summary(crate_dir: Path) -> tuple[str, str, list[str]]:
    """Return (name, description, top-level module files)."""
    cargo = crate_dir / "Cargo.toml"
    name = read_toml_field(cargo, "name") or crate_dir.name
    desc = read_toml_field(cargo, "description") or ""
    src = crate_dir / "src"
    modules: list[str] = []
    if src.is_dir():
        modules = sorted(
            p.name for p in src.iterdir()
            if p.suffix == ".rs" or p.is_dir()
        )
    return name, desc, modules


def first_doc_line(crate_dir: Path) -> str:
    """Fallback description: leading `//!` doc comment of lib.rs / main.rs,
    joined up to the first sentence end (max ~160 chars)."""
    for fname in ("lib.rs", "main.rs"):
        f = crate_dir / "src" / fname
        if not f.exists():
            continue
        try:
            lines = f.read_text(encoding="utf-8").splitlines()[:10]
        except OSError:
            continue
        parts: list[str] = []
        for line in lines:
            line = line.strip()
            if not line.startswith("//!"):
                if parts:
                    break
                continue
            parts.append(line.lstrip("/! ").strip())
            joined = " ".join(parts)
            if joined.endswith(".") or len(joined) > 160:
                return joined
        if parts:
            return " ".join(parts)
    return ""


def main() -> None:
    root = Path.cwd()
    if not (root / "CLAUDE.md").exists():
        sys.exit("Error: CLAUDE.md not found — run from the project root.")

    out: list[str] = [
        "# Project Tree & Knowledge Base",
        "",
        "> Auto-generated by `.claude/skills/project-knowledge/scripts/generate_tree.py`.",
        "> Do not edit by hand — re-run the script after structural changes.",
        "> Read this file INSTEAD of globbing/exploring when you need to locate code.",
        "",
        "## Directory tree",
        "",
        "```",
        f"{root.name}/",
        *tree_lines(root),
        "```",
        "",
    ]

    # ---- Crates ----
    crates_dir = root / "crates"
    if crates_dir.is_dir():
        out += ["## Crates", "", "| Crate | Purpose | Top-level modules |", "|---|---|---|"]
        for crate_dir in sorted(p for p in crates_dir.iterdir() if p.is_dir()):
            name, desc, modules = crate_summary(crate_dir)
            if not desc:
                desc = first_doc_line(crate_dir)
            mods = ", ".join(f"`{m}`" for m in modules) or "-"
            out.append(f"| `{name}` | {desc} | {mods} |")
        out.append("")

    # ---- Frontend ----
    desktop_src = root / "apps" / "desktop" / "src"
    if desktop_src.is_dir():
        out += ["## Frontend (apps/desktop/src)", ""]
        for p in sorted(desktop_src.rglob("*")):
            if p.is_file() and not excluded(p):
                out.append(f"- `{p.relative_to(root).as_posix()}`")
        out.append("")

    # ---- Tauri commands (IPC surface) ----
    tauri_src = root / "apps" / "desktop" / "src-tauri" / "src"
    if tauri_src.is_dir():
        cmds: list[str] = []
        for rs in tauri_src.rglob("*.rs"):
            try:
                text = rs.read_text(encoding="utf-8")
            except OSError:
                continue
            for m in re.finditer(
                r"#\[tauri::command[^\]]*\]\s*(?:pub\s+)?(?:async\s+)?fn\s+(\w+)", text
            ):
                cmds.append(f"- `{m.group(1)}` ({rs.relative_to(root).as_posix()})")
        if cmds:
            out += ["## Tauri IPC commands", "", *sorted(cmds), ""]

    # ---- Key docs ----
    out += ["## Key documents", ""]
    for doc in ("CLAUDE.md", "README.md", "docs/ENGINEERING_DESIGN.md",
                "docs/FABLE5_PROMPT_PLAN.md", ".claude/PROGRESS.md"):
        if (root / doc).exists():
            out.append(f"- `{doc}`")
    out.append("")

    output_path = root / ".claude" / "skills" / "project-knowledge" / "tree.md"
    output_path.write_text("\n".join(out), encoding="utf-8")
    print(f"OK  wrote {output_path.name}: {len(out)} lines")


if __name__ == "__main__":
    main()
